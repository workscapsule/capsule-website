// Now generate galleryData.ts
let content = `import { GalleryItem } from '../types';\n\n`;
content += `export const galleryCategories = [\n`;
for (const cat of Object.keys(categoryPhotos)) {
  content += `  '${cat}',\n`;
}
content += `] as const;\n\n`;
content += `export type GalleryCategoryName = typeof galleryCategories[number];\n\n`;
content += `export const galleryData: GalleryItem[] = [\n`;

let totalCount = 0;
for (const [catName, photos] of Object.entries(categoryPhotos)) {
  const catSlug = catName.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  photos.forEach((photoId, idx) => {
    totalCount++;
    const itemNum = String(idx + 1).padStart(2, '0');
    content += `  {\n`;
    content += `    id: 'gallery-${catSlug}-${itemNum}',\n`;
    content += `    title: '${catName} Work ${itemNum}',\n`;
    content += `    category: '${catName}',\n`;
    content += `    location: 'Bengaluru, Karnataka',\n`;
    content += `    image: 'https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=800&q=80',\n`;
    content += `    description: 'Executed by Capsule Company in Bengaluru.',\n`;
    content += `    featured: ${idx < 3}\n`;
    content += `  },\n`;
  });
}
content += `];\n`;

fs.writeFileSync('src/data/galleryData.ts', content);
